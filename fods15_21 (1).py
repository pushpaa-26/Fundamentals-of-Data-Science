# Step 1: Import required libraries
import pandas as pd
import numpy as np
import scipy.stats as stats
from google.colab import files

# Step 2: Upload the CSV dataset
print("Upload the 21_rare_element_concentration_dataset.csv file")
uploaded = files.upload()

# Step 3: Read the uploaded CSV file
file_name = list(uploaded.keys())[0]
df = pd.read_csv(file_name)

# Step 4: Display the dataset
print("\nDataset Preview:")
print(df.head())

# Step 5: Extract concentration values
data = df.select_dtypes(include=[np.number]).iloc[:, 0].dropna().values

if len(data) < 2:
    raise ValueError("Dataset must contain at least two numerical measurements.")

print("\nTotal Number of Measurements:", len(data))

# Step 6: Get user inputs
sample_size = int(input("\nEnter sample size: "))
confidence_level = float(input("Enter confidence level (90, 95, 99): "))
precision = float(input("Enter desired level of precision: "))

# Step 7: Validate user inputs
if sample_size < 2 or sample_size > len(data):
    raise ValueError("Sample size must be between 2 and the total measurements.")

if confidence_level <= 0 or confidence_level >= 100:
    raise ValueError("Confidence level must be between 0 and 100.")

if precision <= 0:
    raise ValueError("Precision must be greater than zero.")

# Step 8: Select a random sample
sample = np.random.choice(data, size=sample_size, replace=False)

# Step 9: Calculate point estimate
sample_mean = np.mean(sample)
sample_std = np.std(sample, ddof=1)

print("\nPoint Estimation:")
print("Sample Mean:", round(sample_mean, 4))
print("Sample Standard Deviation:", round(sample_std, 4))

# Step 10: Calculate confidence interval
alpha = 1 - confidence_level / 100

t_critical = stats.t.ppf(1 - alpha / 2, df=sample_size - 1)

standard_error = sample_std / np.sqrt(sample_size)

margin_error = t_critical * standard_error

lower_limit = sample_mean - margin_error
upper_limit = sample_mean + margin_error

print("\nConfidence Interval:")
print("Confidence Level:", confidence_level, "%")
print("Lower Limit:", round(lower_limit, 4))
print("Upper Limit:", round(upper_limit, 4))
print("Margin of Error:", round(margin_error, 4))

# Step 11: Calculate required sample size
population_std = np.std(data, ddof=1)

z_critical = stats.norm.ppf(1 - alpha / 2)

required_sample_size = np.ceil(
    (z_critical * population_std / precision) ** 2
)

print("\nRequired Sample Size:")
print("For the desired precision:", int(required_sample_size))

# Step 12: Display final conclusion
print("\nFinal Result:")
print("The estimated average concentration is:",
      round(sample_mean, 4))

print("The", confidence_level,
      "% confidence interval is between",
      round(lower_limit, 4), "and",
      round(upper_limit, 4))

if margin_error <= precision:
    print("Desired precision has been achieved.")
else:
    print("Desired precision has not been achieved.")
    print("Consider increasing the sample size.")

# Step 13: Save the results
results = pd.DataFrame({
    'Sample Size': [sample_size],
    'Confidence Level': [confidence_level],
    'Sample Mean': [sample_mean],
    'Lower Limit': [lower_limit],
    'Upper Limit': [upper_limit],
    'Margin of Error': [margin_error],
    'Required Sample Size': [required_sample_size]
})

