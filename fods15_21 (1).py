def calculate_ci(data):
    n = len(data)
    mean = data.mean()
    std = data.std(ddof=1)
    standard_error = stats.sem(data)

    t_critical = stats.t.ppf(0.975, df=n-1)

    margin_error = t_critical * standard_error

    lower = mean - margin_error
    upper = mean + margin_error

    return mean, lower, upper, n

