from google.colab import files
import matplotlib.pyplot as plt
import pandas as pd

# File-ai upload seyyuratharku (sample_text.txt-ai select seyyungal)
uploaded = files.upload()

# File name-ai automatic-ah eduthukollum
file_name = list(uploaded.keys())[0]

# Text file-ai padithu, words-ah split seyyuvathu
with open(file_name, 'r', encoding='utf-8') as file:
  text = file.read()

print('File Successfully Uploaded and Read!')
from collections import Counter
import re

# Text-ai lowercase-aakki, punctuation-galai neekkuthal
words = re.findall(r'\b\w+\b', text.lower())

# Ovvoru word-in count-aiyum calculate seyyuvathu
word_counts = Counter(s for s in words if len(s) > 2)  # 2 letter-ku kooduthal ulla words mattum

# Top 10 most common words-ai eduthukolluthal
common_words = word_counts.most_common(10)
df_words = pd.DataFrame(common_words, columns=['Word', 'Frequency'])

print('Top 10 Words Frequency:')
print(df_words)

# Bar plot create seyyuvathu
plt.figure(figsize=(10, 5))
plt.bar(
    df_words['Word'],
    df_words['Frequency'],
    color='mediumseagreen',
    edgecolor='darkgreen',
)
plt.title(
    'Top 10 Word Frequency Distribution - Bar Plot',
    fontsize=14,
    fontweight='bold',
)
plt.xlabel('Words', fontsize=12)
plt.ylabel('Frequency Count', fontsize=12)
plt.grid(axis='y', linestyle='--', alpha=0.6)
plt.tight_layout()
plt.show()

