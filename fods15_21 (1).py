# Step 1: Import required libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats
from google.colab import files

# Step 2: Upload the CSV dataset
print("Upload the 20_AB_Testing_Website_Dataset.csv file")
uploaded = files.upload()

# Step 3: Read the uploaded CSV file
file_name = list(uploaded.keys())[0]
df = pd.read_csv(file_name)

# Step 4: Display the dataset
print("\nDataset Preview:")
print(df.head())

print("\nAvailable Columns:")
print(df.columns.tolist())

# Step 5: Identify the group and conversion columns
df.columns = df.columns.str.strip()

group_column = None
conversion_column = None

for col in df.columns:
    name = col.lower().replace("_", "").replace(" ", "")

    if name in ['group', 'design', 'website', 'variant', 'abgroup']:
        group_column = col

    if name in ['converted', 'conversion', 'conversionrate',
                'conversionstatus', 'isconverted']:
        conversion_column = col

# Check columns
if group_column is None or conversion_column is None:
    raise ValueError(
        "Could not identify the Group or Conversion column. "
        "Check the available column names above."
    )

# Step 6: Separate Design A and Design B
df[conversion_column] = pd.to_numeric(
    df[conversion_column], errors='coerce'
)

df = df.dropna(subset=[group_column, conversion_column])

group_a = df[df[group_column].astype(str).str.strip().str.upper() == 'A']
group_b = df[df[group_column].astype(str).str.strip().str.upper() == 'B']

if len(group_a) == 0 or len(group_b) == 0:
    raise ValueError("Design A or Design B was not found in the dataset.")

# Step 7: Calculate conversion rates
mean_a = group_a[conversion_column].mean()
mean_b = group_b[conversion_column].mean()

print("\nConversion Rate Analysis:")
print("Design A Conversion Rate:", round(mean_a * 100, 2), "%")
print("Design B Conversion Rate:", round(mean_b * 100, 2), "%")

print("\nNumber of Visitors:")
print("Design A:", len(group_a))
print("Design B:", len(group_b))

# Step 8: Perform statistical hypothesis testing
# H0: Both designs have equal conversion rates
# H1: Both designs have different conversion rates

a = group_a[conversion_column].values
b = group_b[conversion_column].values

if set(df[conversion_column].unique()).issubset({0, 1}):
    # Two-proportion Z-test for binary conversion data
    success_a = int(a.sum())
    success_b = int(b.sum())

    p_pool = (success_a + success_b) / (len(a) + len(b))

    standard_error = np.sqrt(
        p_pool * (1 - p_pool) * (1/len(a) + 1/len(b))
    )

    if standard_error == 0:
        z_score = 0
        p_value = 1
    else:
        z_score = (mean_a - mean_b) / standard_error
        p_value = 2 * stats.norm.sf(abs(z_score))

else:
    # Independent t-test for continuous conversion-rate data
    t_statistic, p_value = stats.ttest_ind(a, b, equal_var=False)
    z_score = t_statistic

print("\nHypothesis Testing Results:")
print("Test Statistic:", round(z_score, 4))
print("P-value:", round(p_value, 6))

# Step 9: Display the conclusion
alpha = 0.05

print("\nFinal Conclusion:")

if p_value < alpha:
    print("Reject the Null Hypothesis.")
    print("There is a statistically significant difference")
    print("between Website Design A and Design B.")
else:
    print("Fail to Reject the Null Hypothesis.")
    print("There is no statistically significant difference")
    print("between Website Design A and Design B.")

if mean_a > mean_b:
    print("Website Design A has a higher conversion rate.")
elif mean_b > mean_a:
    print("Website Design B has a higher conversion rate.")
else:
    print("Both designs have equal conversion rates.")

# Step 10: Visualize conversion rates
plt.figure(figsize=(8, 5))

sns.barplot(
    x=['Design A', 'Design B'],
    y=[mean_a * 100, mean_b * 100]
)

plt.xlabel("Website Design")
plt.ylabel("Conversion Rate (%)")
plt.title("A/B Testing - Conversion Rate Comparison")
plt.show()

# Step 11: Draw boxplots
plt.figure(figsize=(8, 5))

